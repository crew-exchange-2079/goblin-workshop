"""Which Quadlet keys each Podman release accepts.

keydb.json is generated by tools/extract_keys.py from the supported-key
tables in Podman's pkg/systemd/quadlet/quadlet.go at each vX.Y.0 tag, so a
key's "added" version is the first minor release whose quadlet accepted it.
"""

import json
import re
from importlib import resources

VERSION_RE = re.compile(r"^v?(\d+)\.(\d+)(?:\.(\d+))?(?:[-+~].*)?$")


class VersionError(ValueError):
    pass


def parse_version(text):
    m = VERSION_RE.match(text.strip())
    if not m:
        raise VersionError(f"not a Podman version: {text!r} (expected e.g. 5.2 or 5.2.1)")
    return (int(m.group(1)), int(m.group(2)), int(m.group(3) or 0))


def fmt(version):
    return "%d.%d" % version[:2]


class KeyDB:
    def __init__(self, data):
        self.versions = [parse_version(v) for v in data["versions"]]
        self.sections = {}
        for section, keys in data["sections"].items():
            self.sections[section] = {
                k: {
                    "added": parse_version(v["added"]),
                    "removed": parse_version(v["removed"]) if v["removed"] else None,
                    "deprecated": v["deprecated"],
                }
                for k, v in keys.items()
            }

    @classmethod
    def load(cls):
        text = resources.files("quadlet_lint").joinpath("keydb.json").read_text(encoding="utf-8")
        return cls(json.loads(text))

    @property
    def oldest(self):
        return self.versions[0]

    @property
    def newest(self):
        return self.versions[-1]

    def keys(self, section):
        return self.sections.get(section, {})

    def status(self, section, key, target):
        """("ok" | "unknown" | "too-new" | "removed", info dict or None).

        Only major.minor of target is compared: the table is sampled at .0
        tags, so a key added in a patch release shows up at the next minor.
        """
        info = self.keys(section).get(key)
        if info is None:
            return "unknown", None
        t = target[:2]
        if t < info["added"][:2]:
            return "too-new", info
        if info["removed"] is not None and t >= info["removed"][:2]:
            return "removed", info
        return "ok", info

    def known_at(self, section, target):
        return sorted(k for k in self.keys(section) if self.status(section, k, target)[0] == "ok")
