"""Write SCAD, render STL with headless OpenSCAD, check the mesh and the part's spec, export 3MF (and
optionally a PNG preview), write a manifest.

Output goes into a directory that must not exist yet; it is created with
os.mkdir (so an existing path, file or symlink is refused) and files are
opened with mode "x". Only fixed filenames derived from the validated
``name`` are written.
"""

import hashlib
import json
import math
import os
import platform
import shutil
import subprocess
import tempfile

from . import __version__, export, mesh, speccheck

HERE = os.path.dirname(os.path.abspath(__file__))
SCAD_DIR = os.path.join(os.path.dirname(HERE), "scad")
BBOX_TOL_MM = 0.01


class ToolError(Exception):
    pass


def _lit(v):
    """Render a validated value as an OpenSCAD literal. Only numbers, bools and lists pass."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        if not math.isfinite(v):
            raise ValueError("non-finite value reached SCAD writer")
        return repr(float(v)) if isinstance(v, float) else str(v)
    if isinstance(v, list):
        return "[" + ", ".join(_lit(x) for x in v) + "]"
    raise TypeError("refusing to write %r into SCAD" % type(v).__name__)


def scad_source(cfg, geo):
    with open(os.path.join(SCAD_DIR, geo["module"] + ".scad"), encoding="utf-8") as f:
        lib = f.read()
    args = ",\n    ".join("%s = %s" % (k, _lit(v)) for k, v in geo["args"].items())
    header = ("// Generated by rackparts %s from input %s (sha256 %s).\n"
              "// Self-contained: the module source below is copied from rack-parts/scad/.\n"
              "// SYNTHETIC/UNVERIFIED FIT: check every dimension against your own measurements.\n\n"
              % (__version__, cfg["name"], input_hash(cfg)))
    return header + lib + "\n%s(\n    %s\n);\n" % (geo["module"], args)


def canonical_json(obj):
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), allow_nan=False)


def input_hash(cfg):
    return hashlib.sha256(canonical_json(cfg).encode()).hexdigest()


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def tool_version(exe, arg="--version"):
    try:
        r = subprocess.run([exe, arg], capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return (r.stdout + r.stderr).strip().splitlines()[0] if (r.stdout + r.stderr).strip() else None


def render_stl(openscad, scad_path, stl_path, timeout):
    cmd = [openscad, "--export-format", "binstl", "-o", stl_path, scad_path]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout,
                           cwd=os.path.dirname(scad_path), stdin=subprocess.DEVNULL)
    except subprocess.TimeoutExpired:
        raise ToolError("openscad timed out after %ds" % timeout)
    log = r.stderr
    if r.returncode != 0 or not os.path.exists(stl_path):
        raise ToolError("openscad failed (exit %d):\n%s" % (r.returncode, log[-4000:]))
    for bad in ("WARNING", "ERROR"):
        if bad in log:
            raise ToolError("openscad reported a %s; refusing output:\n%s" % (bad.lower(), log[-4000:]))
    return log


def check_bbox(rep, expected):
    diffs = [abs(rep["bbox_min"][i] - expected["min"][i]) for i in range(3)]
    diffs += [abs(rep["bbox_max"][i] - expected["max"][i]) for i in range(3)]
    return max(diffs) <= BBOX_TOL_MM, max(diffs)


def _write_new(path, data):
    mode = "xb" if isinstance(data, bytes) else "x"
    with open(path, mode, **({} if isinstance(data, bytes) else {"encoding": "utf-8"})) as f:
        f.write(data)


def generate(cfg, geo, out_dir, openscad=None, admesh=None, scad_only=False, timeout=300, png=False):
    """Returns the manifest dict. Raises FileExistsError, ToolError or mesh.MeshError."""
    exe = None
    if not scad_only:
        exe = openscad or shutil.which("openscad")
        if not exe:
            raise ToolError("openscad not found on PATH (use --scad-only to skip rendering)")
    name = cfg["name"]
    src = scad_source(cfg, geo)

    os.makedirs(out_dir)  # creates parents; leaf existing still raises FileExistsError: never clobber
    created = []
    try:
        scad_path = os.path.join(out_dir, name + ".scad")
        _write_new(scad_path, src)
        created.append(scad_path)
        manifest = {
            "manifest_version": 1,
            "generator": {"name": "rackparts", "version": __version__},
            "tools": {"python": platform.python_version()},
            "notice": ("Synthetic/unverified geometry. No strength, load or fit rating. Not tested on a printer or "
                       "installed in a rack. Check every dimension against your own measurements."),
            "input": {"sha256": input_hash(cfg), "parameters": cfg},
            "derived": geo["derived"],
            "expected_bbox_mm": geo["expected_bbox"],
            "print_orientation_suggestion": geo["print_orientation_suggestion"],
            **({"physical_use": geo["physical_use"]} if "physical_use" in geo else {}),
            "files": {"scad": {"path": os.path.basename(scad_path), "sha256": sha256_file(scad_path),
                               "bytes": os.path.getsize(scad_path)}},
        }
        if not scad_only:
            manifest["tools"]["openscad"] = tool_version(exe)
            stl_path = os.path.join(out_dir, name + ".stl")
            with tempfile.TemporaryDirectory(prefix="rackparts-") as tmp:
                tmp_scad = os.path.join(tmp, "part.scad")
                tmp_stl = os.path.join(tmp, "part.stl")
                _write_new(tmp_scad, src)
                render_stl(exe, tmp_scad, tmp_stl, timeout)
                rep = mesh.analyse(mesh.read_stl(tmp_stl))
                ok_bbox, err = check_bbox(rep, geo["expected_bbox"])
                rep["bbox_matches_expected"] = ok_bbox
                rep["bbox_max_deviation_mm"] = round(err, 5)
                if not ok_bbox:
                    rep["problems"].append("bounding box deviates %.4f mm from the validated design" % err)
                if rep["shells"] != 1:
                    rep["problems"].append("expected 1 connected shell, found %d" % rep["shells"])
                ad_exe = admesh or shutil.which("admesh")
                rep["admesh"] = None
                if ad_exe:
                    manifest["tools"]["admesh"] = tool_version(ad_exe)
                    ad = mesh.run_admesh(tmp_stl, ad_exe)
                    if ad.get("parts") != rep["shells"]:
                        ad["problems"].append("admesh part count %s != %d shells" % (ad.get("parts"), rep["shells"]))
                    ad["ok"] = not ad["problems"]
                    rep["admesh"] = ad
                    rep["problems"].extend(ad["problems"])
                tris = mesh.read_stl(tmp_stl)
                if not rep["problems"]:
                    # the features the validated numbers describe must exist in the mesh
                    spec_rep = speccheck.run(cfg, geo, tris)
                    manifest["spec_check"] = spec_rep
                    rep["problems"].extend(spec_rep["problems"])
                rep["ok"] = not rep["problems"]
                if not rep["ok"]:
                    raise mesh.MeshError("rendered mesh rejected: " + "; ".join(rep["problems"]))
                with open(tmp_stl, "rb") as f:
                    _write_new(stl_path, f.read())
                created.append(stl_path)
            manifest["mesh"] = rep
            manifest["files"]["stl"] = {"path": os.path.basename(stl_path), "sha256": sha256_file(stl_path),
                                        "bytes": os.path.getsize(stl_path)}
            path_3mf = os.path.join(out_dir, name + ".3mf")
            created.append(path_3mf)
            export.write_3mf(tris, path_3mf, name)
            if mesh.geometry_hash(export.read_3mf(path_3mf)) != rep["geometry_sha256"]:
                raise mesh.MeshError("3MF export does not reproduce the checked STL geometry")
            manifest["files"]["3mf"] = {"path": os.path.basename(path_3mf), "sha256": sha256_file(path_3mf),
                                        "bytes": os.path.getsize(path_3mf)}
            if png:
                png_path = os.path.join(out_dir, name + ".png")
                created.append(png_path)
                export.write_png(tris, png_path, **geo.get("preview", {}))
                manifest["files"]["png"] = {"path": os.path.basename(png_path), "sha256": sha256_file(png_path),
                                            "bytes": os.path.getsize(png_path),
                                            "note": "orthographic preview only; not for measurement"}
        man_path = os.path.join(out_dir, "manifest.json")
        _write_new(man_path, json.dumps(manifest, indent=2, sort_keys=True, allow_nan=False) + "\n")
        created.append(man_path)
    except BaseException:
        for p in created:
            try:
                os.unlink(p)
            except OSError:
                pass
        try:
            os.rmdir(out_dir)
        except OSError:
            pass
        raise
    return manifest
